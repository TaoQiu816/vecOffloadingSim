# Baseline policies (obs-only except random generator state)
# ------------------------------

class BasePolicy:
    name = "base"

    def reset(self, seed: int) -> None:
        self.rng = np.random.default_rng(seed)

    def select_action(self, obs_list: List[Dict]) -> List[Dict]:
        raise NotImplementedError


class RandomLegalPolicy(BasePolicy):
    name = "random_legal"

    def select_action(self, obs_list: List[Dict]) -> List[Dict]:
        actions = []
        for obs in obs_list:
            subtask = _choose_ready_subtask_random(obs, self.rng)
            valid_targets = _valid_indices(np.asarray(obs.get("action_mask", []), dtype=np.float32))
            if valid_targets.size == 0:
                target = 0
            else:
                target = int(self.rng.choice(valid_targets))
            actions.append(_build_action(obs, subtask=subtask, target=target, power=0.5))
        return actions


class LocalOnlyPolicy(BasePolicy):
    name = "local_only"

    def select_action(self, obs_list: List[Dict]) -> List[Dict]:
        actions = []
        for obs in obs_list:
            # choose first READY (or fallback) but always local target=0
            subtask = _choose_ready_subtask_first(obs)
            actions.append(_build_action(obs, subtask=subtask, target=0, power=1.0))
        return actions


class RSUPreferPolicy(BasePolicy):
    name = "rsu_prefer"

    def select_action(self, obs_list: List[Dict]) -> List[Dict]:
        actions = []
        for obs in obs_list:
            subtask = _choose_ready_subtask_first(obs)
            rsu_slots = _target_indices_by_type(obs, target_type=2)
            if rsu_slots:
                target = int(rsu_slots[0])
            else:
                target = 0  # fallback local
            actions.append(_build_action(obs, subtask=subtask, target=target, power=0.7))
        return actions


class GreedyEFTLikePolicy(BasePolicy):
    """Observation-only snapshot heuristic (non-oracle, simplified EFT-like).

    Subtask rule:
      among READY subtasks, choose smallest urgency (node_x[:,6], lower means more urgent);
      tie-break by larger remaining compute (node_x[:,0]).
    Target rule:
      among legal targets in action_mask, choose minimal snapshot score built from resource_raw/rate_prev.
    """
    name = "greedy_eft_like"

    def _choose_subtask(self, obs: Dict) -> int:
        # Prefer env-provided suggestion if it is currently schedulable (obs-only usage).
        submask = np.asarray(obs.get("subtask_mask", obs.get("task_mask", [])), dtype=np.float32).reshape(-1)
        try:
            env_idx = int(obs.get("subtask_index", -1))
            if 0 <= env_idx < len(submask) and submask[env_idx] > 0.0:
                return env_idx
        except Exception:
            pass
        node_x = np.asarray(obs.get("node_x", []), dtype=np.float32)
        ready = np.where(submask > 0.0)[0]
        if ready.size == 0:
            return _choose_ready_subtask_first(obs)
        # Fallback: urgency-first among READY, tie-break by larger remaining compute.
        best = None
        best_key = None
        for i in ready.tolist():
            urg = _safe_float(node_x[i][6] if i < len(node_x) and len(node_x[i]) > 6 else 1.0, 1.0)
            rem_comp = _safe_float(node_x[i][0] if i < len(node_x) and len(node_x[i]) > 0 else 0.0, 0.0)
            key = (urg, -rem_comp, i)
            if best_key is None or key < best_key:
                best_key = key
                best = i
        return int(best if best is not None else int(ready[0]))

    def select_action(self, obs_list: List[Dict]) -> List[Dict]:
        actions = []
        for obs in obs_list:
            subtask = self._choose_subtask(obs)
            action_mask = np.asarray(obs.get("action_mask", []), dtype=np.float32).reshape(-1)
            valid_targets = np.where(action_mask > 0.0)[0]
            if valid_targets.size == 0:
                actions.append(_build_action(obs, subtask=subtask, target=0, power=0.7))
                continue
            best_t = None
            best_score = None
            for t in valid_targets.tolist():
                score = _estimate_target_score_from_obs(obs, subtask_idx=subtask, target_idx=int(t))
                if best_score is None or score < best_score:
                    best_score = score
                    best_t = int(t)
            actions.append(_build_action(obs, subtask=subtask, target=(best_t if best_t is not None else 0), power=0.7))
        return actions


