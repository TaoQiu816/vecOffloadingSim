def assert_default_scene_invariants() -> None:
    """Fail fast if the codebase baseline deviates from the agreed default scenario."""
    assert float(Cfg.DT) == 0.1, f"Expected DT=0.1, got {Cfg.DT}"
    assert int(Cfg.MAX_STEPS) == 200, f"Expected MAX_STEPS=200, got {Cfg.MAX_STEPS}"
    assert bool(Cfg.TERMINATE_ON_ALL_FINISHED) is True
    assert float(Cfg.VEHICLE_ARRIVAL_RATE) == 0.0
    assert int(Cfg.NUM_VEHICLES) == 20
    assert int(Cfg.NUM_RSU) == 3
    assert str(Cfg.CANDIDATE_MODE).upper() == "ALL"
    assert bool(Cfg.ENABLE_RSU_SELECTION) is True
    # Derived values in current code default baseline.
    assert int(Cfg.MAX_NEIGHBORS) == 19, f"Expected MAX_NEIGHBORS=19, got {Cfg.MAX_NEIGHBORS}"
    assert int(Cfg.MAX_TARGETS) == 23, f"Expected MAX_TARGETS=23, got {Cfg.MAX_TARGETS}"
    assert str(getattr(Cfg, "REWARD_SCHEME", "")) == "UNIFIED"
    assert bool(getattr(Cfg, "ENABLE_PBRS", False)) is False


