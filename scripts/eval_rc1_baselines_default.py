@dataclass
class EpRecord:
    seed: int
    baseline: str
    terminated: bool
    truncated: bool
    terminated_reason: str
    ep_reward_sum: float
    ep_steps: int
    metrics: Dict[str, float] = field(default_factory=dict)


@dataclass
class Summary:
    baseline: str
    n: int
    seeds: List[int]
    rows: List[EpRecord]


def _mean(xs: Sequence[float]) -> float:
    vals = [float(x) for x in xs if x is not None and math.isfinite(float(x))]
    return float(np.mean(vals)) if vals else float("nan")


def _pctl(xs: Sequence[float], q: float) -> float:
    vals = [float(x) for x in xs if x is not None and math.isfinite(float(x))]
    return float(np.percentile(vals, q)) if vals else float("nan")


def run_policy_episodes(policy_factory: Callable[[], BasePolicy], seeds: Sequence[int]) -> Summary:
    env = VecOffloadingEnv()
    baseline_name = policy_factory().name
    rows: List[EpRecord] = []

    for ep_seed in seeds:
        random.seed(int(ep_seed))
        np.random.seed(int(ep_seed))

        policy = policy_factory()
        policy.reset(int(ep_seed))

        # Keep env metrics seed metadata aligned with this episode seed.
        try:
            Cfg.SEED = int(ep_seed)
        except Exception:
            pass
        obs_list, _ = env.reset(seed=int(ep_seed))

        ep_reward_sum = 0.0
        ep_steps = 0
        terminated = False
        truncated = False
        info = {}

        for _ in range(int(Cfg.MAX_STEPS)):
            actions = policy.select_action(obs_list)
            next_obs, rewards, terminated, truncated, info = env.step(actions)
            ep_reward_sum += float(np.sum(np.asarray(rewards, dtype=np.float64)))
            ep_steps += 1
            obs_list = next_obs
            if terminated or truncated:
                break

        # env normally writes episode_metrics at done. Fallback for safety if a path exits without done.
        if not (terminated or truncated):
            if hasattr(env, "_log_episode_stats"):
                env._log_episode_stats(False, True)
                terminated = False
                truncated = True
                info = getattr(env, "_last_episode_metrics", {})

        ep_metrics = {}
        if isinstance(info, dict):
            if isinstance(info.get("episode_metrics"), dict):
                ep_metrics = dict(info["episode_metrics"])
            elif "task_success_rate" in info:
                ep_metrics = dict(info)
        if not ep_metrics and hasattr(env, "_last_episode_metrics"):
            ep_metrics = dict(getattr(env, "_last_episode_metrics", {}) or {})

        term_reason = str(info.get("terminated_reason", ep_metrics.get("terminated_reason", "none"))) if isinstance(info, dict) else str(ep_metrics.get("terminated_reason", "none"))

        rows.append(EpRecord(
            seed=int(ep_seed),
            baseline=baseline_name,
            terminated=bool(terminated),
            truncated=bool(truncated),
            terminated_reason=term_reason,
            ep_reward_sum=float(ep_reward_sum),
            ep_steps=int(ep_steps),
            metrics=ep_metrics,
        ))

    try:
        env.close()
    except Exception:
        pass

    return Summary(baseline=baseline_name, n=len(rows), seeds=[int(s) for s in seeds], rows=rows)


def summarize(summary: Summary) -> Dict[str, float]:
    rows = summary.rows
    n = max(len(rows), 1)
    term_success = sum(1 for r in rows if (r.terminated and r.terminated_reason == "success_all_done")) / n
    term_idle = sum(1 for r in rows if (r.terminated and r.terminated_reason == "idle")) / n
    trunc_time = sum(1 for r in rows if r.truncated) / n

    tsr = _mean([r.metrics.get("task_success_rate", float("nan")) for r in rows])
    ssr = _mean([r.metrics.get("subtask_success_rate", float("nan")) for r in rows])
    illegal_rate = _mean([r.metrics.get("illegal_action_rate", float("nan")) for r in rows])
    d_local = _mean([r.metrics.get("decision_frac_local", float("nan")) for r in rows])
    d_rsu = _mean([r.metrics.get("decision_frac_rsu", float("nan")) for r in rows])
    d_v2v = _mean([r.metrics.get("decision_frac_v2v", float("nan")) for r in rows])

    avg_completed_tasks = _mean([r.metrics.get("completed_tasks_count", float("nan")) for r in rows])
    avg_completed_subtasks = _mean([
        _safe_float(r.metrics.get("subtask_success_rate", 0.0), 0.0) * _safe_float(r.metrics.get("total_subtasks", 0.0), 0.0)
        for r in rows
    ])

    rewards = [r.ep_reward_sum for r in rows]
    steps = [r.ep_steps for r in rows]

    return {
        "episodes": len(rows),
        "seed_first": rows[0].seed if rows else None,
        "seed_last": rows[-1].seed if rows else None,
        "term_success_all_done": term_success,
        "term_idle": term_idle,
        "trunc_time_limit": trunc_time,
        "task_success_rate": tsr,
        "subtask_success_rate": ssr,
        "ep_reward_mean": _mean(rewards),
        "ep_reward_p50": _pctl(rewards, 50),
        "ep_reward_p90": _pctl(rewards, 90),
        "ep_steps_mean": _mean(steps),
        "illegal_action_rate": illegal_rate,
        "decision_frac_local": d_local,
        "decision_frac_rsu": d_rsu,
        "decision_frac_v2v": d_v2v,
        "completed_tasks_mean": avg_completed_tasks,
        "completed_subtasks_mean": avg_completed_subtasks,
    }


def _fmt_pct(x: float) -> str:
    return "nan" if not math.isfinite(float(x)) else f"{100.0 * float(x):5.1f}%"


def _fmt_num(x: float, nd=3) -> str:
    return "nan" if not math.isfinite(float(x)) else f"{float(x):.{nd}f}"


def print_table(summaries: List[Summary]) -> None:
    print("\n[RC1 Default Baseline Learnability Check] Summary")
    headers = [
        "baseline", "N", "succ_all", "idle", "trunc", "task_SR", "subtask_SR",
        "R_ep_mean", "R_ep_p50", "R_ep_p90", "steps_mean", "illegal", "L", "R", "V", "done_tasks",
    ]
    print(" | ".join(headers))
    print(" | ".join(["---"] * len(headers)))
    for s in summaries:
        m = summarize(s)
        row = [
            s.baseline,
            str(m["episodes"]),
            _fmt_pct(m["term_success_all_done"]),
            _fmt_pct(m["term_idle"]),
            _fmt_pct(m["trunc_time_limit"]),
            _fmt_num(m["task_success_rate"]),
            _fmt_num(m["subtask_success_rate"]),
            _fmt_num(m["ep_reward_mean"], 2),
            _fmt_num(m["ep_reward_p50"], 2),
            _fmt_num(m["ep_reward_p90"], 2),
            _fmt_num(m["ep_steps_mean"], 1),
            _fmt_pct(m["illegal_action_rate"]),
            _fmt_pct(m["decision_frac_local"]),
            _fmt_pct(m["decision_frac_rsu"]),
            _fmt_pct(m["decision_frac_v2v"]),
            _fmt_num(m["completed_tasks_mean"], 2),
        ]
        print(" | ".join(row))

    # A compact verdict helper (no hard claims, just pattern hints)
    by_name = {s.baseline: summarize(s) for s in summaries}
    if {"random_legal", "local_only", "rsu_prefer", "greedy_eft_like"}.issubset(by_name.keys()):
        r = by_name["random_legal"]
        l = by_name["local_only"]
        p = by_name["rsu_prefer"]
        g = by_name["greedy_eft_like"]
        print("\n[Quick pattern check]")
        print(
            f"random task_SR={_fmt_num(r['task_success_rate'])}, local={_fmt_num(l['task_success_rate'])}, "
            f"rsu={_fmt_num(p['task_success_rate'])}, greedy={_fmt_num(g['task_success_rate'])}"
        )
        print(
            f"trunc ratios: random={_fmt_pct(r['trunc_time_limit'])}, local={_fmt_pct(l['trunc_time_limit'])}, "
            f"rsu={_fmt_pct(p['trunc_time_limit'])}, greedy={_fmt_pct(g['trunc_time_limit'])}"
        )


def parse_args() -> argparse.Namespace:
    ap = argparse.ArgumentParser(description="Evaluate simple baselines on RC1 default scenario (direct train.py config semantics)")
    ap.add_argument("--episodes", type=int, default=5, help="episodes per baseline")
    ap.add_argument("--seed-start", type=int, default=42, help="first episode seed")
    ap.add_argument("--baselines", nargs="*", default=["random_legal", "local_only", "rsu_prefer", "greedy_eft_like"],
                    choices=["random_legal", "local_only", "rsu_prefer", "greedy_eft_like"], help="subset to run")
    return ap.parse_args()


def main() -> None:
    assert_default_scene_invariants()

    args = parse_args()
    seeds = [int(args.seed_start + i) for i in range(int(args.episodes))]

    # White-box evidence summary (concise, to make runs self-describing)
    print("[WhiteBox] Env API: reset(seed)->(obs_list, info), step(actions)->(obs,reward,terminated,truncated,info)")
    print("  evidence: envs/vec_offloading_env.py:1942, 2766, 4313")
    print("[WhiteBox] Action format: dict{subtask,target,power} parsed in _plan_actions_snapshot")
    print("  evidence: envs/vec_offloading_env.py:_plan_actions_snapshot ~909-932")
    print("[WhiteBox] subtask_mask = READY && not_assigned; action_mask = legal target slots")
    print("  evidence: envs/entities/task_dag.py:198-200 ; envs/vec_offloading_env.py:4733, 5191-5194")
    print(f"[Run] episodes_per_baseline={len(seeds)}, seeds={seeds[0]}..{seeds[-1]} ({len(seeds)} total)")

    registry: Dict[str, Callable[[], BasePolicy]] = {
        "random_legal": RandomLegalPolicy,
        "local_only": LocalOnlyPolicy,
        "rsu_prefer": RSUPreferPolicy,
        "greedy_eft_like": GreedyEFTLikePolicy,
    }

    summaries: List[Summary] = []
    for name in args.baselines:
        print(f"\n[Run] baseline={name}")
        summary = run_policy_episodes(registry[name], seeds=seeds)
        summaries.append(summary)
        m = summarize(summary)
        print(
            f"  task_SR={_fmt_num(m['task_success_rate'])} subtask_SR={_fmt_num(m['subtask_success_rate'])} "
            f"R_ep_mean={_fmt_num(m['ep_reward_mean'],2)} trunc={_fmt_pct(m['trunc_time_limit'])}"
        )

    print_table(summaries)


if __name__ == "__main__":
    main()
