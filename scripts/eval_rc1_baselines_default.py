def _valid_indices(mask: np.ndarray) -> np.ndarray:
    arr = np.asarray(mask, dtype=np.float32).reshape(-1)
    return np.where(arr > 0.0)[0]


def _choose_ready_subtask_first(obs: Dict) -> int:
    submask = np.asarray(obs.get("subtask_mask", obs.get("task_mask", [])), dtype=np.float32).reshape(-1)
    valid = np.where(submask > 0.0)[0]
    if valid.size > 0:
        return int(valid[0])
    try:
        return int(obs.get("subtask_index", 0))
    except Exception:
        return 0


def _choose_ready_subtask_random(obs: Dict, rng: np.random.Generator) -> int:
    submask = np.asarray(obs.get("subtask_mask", obs.get("task_mask", [])), dtype=np.float32).reshape(-1)
    valid = np.where(submask > 0.0)[0]
    if valid.size > 0:
        return int(rng.choice(valid))
    # no-task state fallback (env planner will handle as no-task/illegal-safe path)
    node_valid = np.asarray(obs.get("node_valid_mask", obs.get("task_mask", [])), dtype=np.float32).reshape(-1)
    valid_nodes = np.where(node_valid > 0.0)[0]
    if valid_nodes.size > 0:
        return int(valid_nodes[0])
    return 0


def _target_indices_by_type(obs: Dict, target_type: int) -> List[int]:
    mask = np.asarray(obs.get("action_mask", []), dtype=np.float32).reshape(-1)
    ctype = np.asarray(obs.get("candidate_types", []), dtype=np.int64).reshape(-1)
    out: List[int] = []
    for i in range(min(len(mask), len(ctype))):
        if mask[i] > 0.0 and int(ctype[i]) == int(target_type):
            out.append(int(i))
    return out


def _build_action(obs: Dict, subtask: int, target: int, power: float) -> Dict:
    act = {
        "subtask": int(subtask),
        "target": int(target),
        "power": float(power),
    }
    if "obs_stamp" in obs:
        try:
            act["obs_stamp"] = int(obs["obs_stamp"])
        except Exception:
            pass
    return act


def _safe_float(x, default=0.0) -> float:
    try:
        v = float(x)
        if math.isfinite(v):
            return v
    except Exception:
        pass
    return float(default)


# resource_raw layout in env._get_obs (vec_offloading_env.py):
# col0 cpu_norm, col1 comp_backlog_norm, col2 tx_backlog_norm, col3 dist_norm,
# col4 rel_x, col5 rel_y, col6 rel_speed_norm, col7 contact_norm,
# col8 contention_norm, col9 occupancy_norm

def _estimate_target_score_from_obs(obs: Dict, subtask_idx: int, target_idx: int) -> float:
    """Snapshot-only heuristic score (lower is better), using obs explicit fields only.

    Approx score = comp_backlog + tx_backlog + comp_lb_proxy + tx_lb_proxy + congestion_penalty.
    This is intentionally lightweight and non-oracle.
    """
    raw = np.asarray(obs.get("resource_raw", []), dtype=np.float32)
    ctype = np.asarray(obs.get("candidate_types", []), dtype=np.int64).reshape(-1)
    node_x = np.asarray(obs.get("node_x", []), dtype=np.float32)
    rate_prev = np.asarray(obs.get("rate_prev", []), dtype=np.float32).reshape(-1)
    if target_idx < 0 or target_idx >= len(raw):
        return float("inf")
    rr = raw[target_idx]
    t = int(ctype[target_idx]) if target_idx < len(ctype) else 0

    cpu_norm = max(_safe_float(rr[0], 0.0), 1e-3)
    comp_backlog = _safe_float(rr[1], 0.0)
    tx_backlog = _safe_float(rr[2], 0.0)
    dist_norm = _safe_float(rr[3], 1.0)
    contact_norm = _safe_float(rr[7], 0.0)
    contention_norm = _safe_float(rr[8], 0.0)
    occupancy_norm = _safe_float(rr[9], 0.0)

    rem_data_norm = 0.0
    rem_comp_norm = 0.0
    if subtask_idx >= 0 and subtask_idx < len(node_x):
        # node_x[:,0]=rem_comp_norm, node_x[:,1]=rem_data_norm
        rem_comp_norm = _safe_float(node_x[subtask_idx][0], 0.0)
        rem_data_norm = _safe_float(node_x[subtask_idx][1], 0.0)

    comp_lb_proxy = (rem_comp_norm + comp_backlog) / cpu_norm

    # Local has no input TX. Remote uses previous realized rate or distance proxy.
    tx_lb_proxy = 0.0
    if t in (2, 3):
        rate_hint = 0.0
        if target_idx < len(rate_prev):
            rate_hint = max(rate_hint, _safe_float(rate_prev[target_idx], 0.0))
        if rate_hint <= 1e-6:
            rate_hint = max(1.0 - dist_norm, 1e-3)
        tx_lb_proxy = rem_data_norm / max(rate_hint, 1e-3)

    # EFT-like snapshot score (obs-only): backlog + compute proxy + transmission proxy.
    score = comp_backlog + tx_backlog + comp_lb_proxy + tx_lb_proxy
    if t in (2, 3):
        score += 0.25 * (1.0 - contact_norm) + 0.20 * contention_norm + 0.15 * occupancy_norm
    # Strongly discourage invalid / empty slot types.
    if t <= 0:
        score += 1000.0
    return float(score)


